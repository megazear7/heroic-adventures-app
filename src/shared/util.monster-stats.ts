import type { MonsterType } from "./type.encounter.js";
import type { MonsterStatBlock, MonsterStats, MonsterStatsLevelRange } from "./type.monster-stats.js";

export function getMonsterStatsLevelRange(level: number): MonsterStatsLevelRange {
    const normalizedLevel = Math.max(1, Math.min(30, Math.floor(level) || 1));
    const rangeStart = normalizedLevel % 2 === 0 ? normalizedLevel - 1 : normalizedLevel;
    const rangeEnd = Math.min(30, rangeStart + 1);
    return `levels_${rangeStart}_${rangeEnd}` as MonsterStatsLevelRange;
}

export function getMonsterStatsForEncounterLevel(level: number, monsterType: MonsterType): MonsterStatBlock {
    return MONSTER_STATS[getMonsterStatsLevelRange(level)][monsterType];
}

